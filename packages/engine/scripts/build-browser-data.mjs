/**
 * build-browser-data.mjs — 构建期（仅 node）生成浏览器安全真相数据
 * ----------------------------------------------------------------------------
 * 用 node 侧 resident-loader（依赖 node:fs，仅构建期运行）读取居民真相数据 +
 * engine 真相表，序列化为 packages/web/src/data/truthData.generated.ts。
 * 生成的文件不依赖任何 Node 专属 API，可被浏览器 / Vite 直接打包，用于离线判定。
 *
 * 前置：在 @lunhui/engine 先 `npm run build`（产出 dist/resident-loader.js），
 *       再 `npm run build:browser-data`（或 `node scripts/build-browser-data.mjs`）。
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { loadAllResidents } from '../dist/resident-loader.js';

// 注意：import.meta.url 含文件名，需先 dirname 再向上两级到 packages/，
// 再进入 web/src/data。
const scriptDir = path.dirname(fileURLToPath(import.meta.url));

const residents = loadAllResidents();

const residentSecrets = {};
const facts = [];
const keywords = {};
for (const r of residents) {
  const perResident = {};
  for (const f of r.secretFacts.facts) {
    perResident[f.id] = f.keywords ?? [];
    facts.push(f);
  }
  residentSecrets[r.id] = {
    facts: r.secretFacts.facts,
    truth: r.secretFacts.truth,
  };
  // 注意：fact.id 仅在居民内唯一（r1..r8 都复用 f1/f2/f3），故 keywords 按居民再分一层
  keywords[r.id] = perResident;
}

const data = { residentSecrets, facts, keywords };

const banner = `// AUTO-GENERATED by packages/engine/scripts/build-browser-data.mjs
// DO NOT EDIT BY HAND. 重新生成请运行 \`npm run build:browser-data\`（在 @lunhui/engine）。
// 浏览器安全静态真相数据：供 web 离线客户端做零 token / 零后端的确定性判定。
import type { SecretFacts, Fact } from '@lunhui/engine/types';

export interface BrowserTruthData {
  /** 各居民真相表（facts + truth） */
  residentSecrets: Record<string, SecretFacts>;
  /** 全部事实（跨居民，扁平列表，辅助用） */
  facts: Fact[];
  /** residentId -> (factId -> 触发关键词) 索引，辅助用 */
  keywords: Record<string, Record<string, string[]>>;
}

export const truthData: BrowserTruthData = `;

const footer = `;
`;

const outDir = path.resolve(scriptDir, '../../web/src/data');
mkdirSync(outDir, { recursive: true });
const outFile = path.join(outDir, 'truthData.generated.ts');
writeFileSync(outFile, banner + JSON.stringify(data, null, 2) + footer, 'utf-8');
console.log(`[build-browser-data] wrote ${outFile}`);
console.log(`  residents=${residents.length} facts=${facts.length} keywords=${Object.keys(keywords).length}`);
